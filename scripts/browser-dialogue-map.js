/* eslint-disable @typescript-eslint/no-unused-expressions -- Playwright CLI invokes this function with its page argument. */
async (page) => {
  const check = (value, message) => { if (!value) throw Error(message); };
  const state = () => page.evaluate(() => window.__nachtwache.state());
  await page.goto('http://localhost:3000');
  await page.waitForFunction(() => window.__nachtwache && !document.querySelector('.start-actions .secondary')?.disabled);
  await page.getByRole('button', { name: 'NEUES SPIEL' }).click();
  await page.keyboard.press('m');
  await page.getByText('Die Karte hat Mara.', { exact: true }).waitFor();
  check(!(await state()).hasMap, 'No map before speaking to Mara');
  await page.keyboard.press('m');
  await page.evaluate(() => window.__nachtwache.teleport(-53, -37));
  await page.keyboard.press('e');
  await page.locator('.dialogue-subtitles').waitFor();
  const first = await state();
  check(first.dialogue?.speaker === 'MARA' && first.stage === 0, 'Mara starts the introduction without skipping the mission');
  check(!first.hasMap, 'Map is handed over at the end of the introduction');
  await page.waitForTimeout(6600);
  const afterWait = await state();
  check(afterWait.dialogue.index === 0 && afterWait.elapsed === first.elapsed && afterWait.health === first.health, 'Subtitles persist beyond six seconds and pause the world');
  await page.screenshot({ path: 'output/playwright/dialogue-subtitles.png' });
  await page.keyboard.down('e'); await page.keyboard.down('e'); await page.keyboard.up('e');
  check((await state()).dialogue.index === 1, 'Held E advances only one statement');
  await page.keyboard.press('Space');
  check((await state()).dialogue.index === 2, 'Space advances one statement');
  const ammo = (await state()).ammo;
  await page.mouse.click(640, 350);
  check((await state()).ammo === ammo, 'Clicking during conversation cannot fire');
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'WEITERSPIELEN' }).click();
  check((await state()).dialogue.index === 2, 'Pausing preserves the current statement');
  for (let i = 0; i < 30 && (await state()).dialogue; i++) await page.keyboard.press('Enter');
  const received = await state();
  check(received.hasMap && received.stage === 1 && !received.dialogue, 'Finishing Mara grants the map and activates the market objective');
  await page.keyboard.press('m');
  const map = page.locator('.map-viewport svg');
  await map.waitFor();
  check(await map.getAttribute('viewBox') === '-1200 -1000 2400 2000', 'Overview covers all playable world bounds');
  await page.getByRole('button', { name: 'Mein Standort' }).click();
  check(await map.locator('text').filter({ hasText: 'POLIZEI' }).count() === 1, 'Unvisited places are labelled');
  await page.getByRole('button', { name: 'Ganze Karte', exact: true }).click();
  const beforeZoom = await map.getAttribute('viewBox');
  await page.getByRole('button', { name: 'Karte vergrößern' }).click();
  check(await map.getAttribute('viewBox') !== beforeZoom, 'Zoom button changes the view');
  const bounds = await map.boundingBox();
  await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2);
  await page.mouse.wheel(0, -500);
  await page.waitForTimeout(150);
  const zoomed = await map.getAttribute('viewBox');
  await page.mouse.down(); await page.mouse.move(bounds.x + bounds.width / 2 + 75, bounds.y + bounds.height / 2 + 35, { steps: 5 }); await page.mouse.up();
  check(await map.getAttribute('viewBox') !== zoomed, 'Dragging pans the map');
  await page.getByRole('button', { name: 'Mein Standort' }).click();
  const [x, z, w, h] = (await map.getAttribute('viewBox')).split(' ').map(Number);
  check(received.position[0] >= x && received.position[0] <= x + w && received.position[2] >= z && received.position[2] <= z + h, 'Locate player keeps the player visible');
  await page.screenshot({ path: 'output/playwright/world-map-detail.png' });
  await page.getByRole('button', { name: 'Ganze Karte', exact: true }).click();
  check(await map.getAttribute('viewBox') === beforeZoom, 'Overview button restores the entire world');
  await page.screenshot({ path: 'output/playwright/world-map-overview.png' });
  const paused = (await state()).elapsed;
  await page.waitForTimeout(300);
  check((await state()).elapsed === paused, 'Map pauses world time');
  await page.keyboard.press('m');
  await page.evaluate(() => window.__nachtwache.start());
  check(!(await state()).hasMap && !(await state()).dialogue && (await state()).stage === 0, 'Restart resets map and dialogue');
  return { passed: ['Mara introduction', 'manual subtitles', 'conversation pause', 'input isolation', 'map handover', 'complete world', 'unvisited labels', 'zoom buttons', 'wheel zoom', 'pan', 'player centering', 'overview reset', 'map pause', 'new run reset'] };
}
