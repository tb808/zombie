/* eslint-disable @typescript-eslint/no-unused-expressions -- Playwright CLI invokes this function with its page argument. */
async(page)=>{
  const check=(ok,message)=>{if(!ok)throw Error(message);};
  const ready=()=>page.waitForFunction(()=>window.__nachtwache&&!document.querySelector('.start-actions .secondary')?.disabled,{}, {timeout:90000});
  const state=()=>page.evaluate(()=>window.__nachtwache.state());
  const slot=(area,index)=>page.locator(`[data-slot="${area}-${index}"]`);
  await ready();
  await page.setViewportSize({width:1440,height:1080});
  await page.evaluate(()=>window.__nachtwache.start());
  check(await page.locator('.quickbelt>div').count()===5,'HUD has exactly five slots');
  await page.keyboard.press('i');
  await page.getByRole('heading',{name:'Inventar & Hotbar'}).waitFor();
  const initial=await state();check(!initial.active,'I opens inventory and pauses gameplay');
  check(await page.getByRole('button',{name:'Inventar',exact:true}).getAttribute('aria-pressed')==='true','I selects inventory directly');
  await slot('backpack',0).dragTo(slot('hotbar',0));
  let s=await state();check(s.inventoryLayout.hotbar[0]==='ration'&&s.inventoryLayout.backpack[0]==='pistol','Native drag swaps backpack and occupied hotbar');
  check(JSON.stringify(s.inventory)===JSON.stringify(initial.inventory),'Moving items preserves all quantities');
  await slot('hotbar',2).click();await slot('hotbar',3).click();
  s=await state();check(s.inventoryLayout.hotbar[2]==='water'&&s.inventoryLayout.hotbar[3]==='medkit','Two clicks reorder occupied hotbar slots');
  await slot('backpack',1).click();await slot('backpack',12).click();
  s=await state();check(s.inventoryLayout.backpack[12]==='battery'&&s.inventoryLayout.backpack[1]===null,'Backpack positions are free');
  await slot('hotbar',4).click();await page.getByRole('button',{name:'In den Rucksack',exact:true}).click();
  check((await state()).inventoryLayout.hotbar[4]===null,'Stow clears a hotbar slot');
  await page.locator('[data-item="flare"]').click();await page.getByRole('button',{name:'Auf Hotbar-Platz 5 legen'}).click();
  check((await state()).inventoryLayout.hotbar[4]==='flare','Detail buttons assign hotbar slots');
  await slot('backpack',12).click();await page.keyboard.press('5');
  s=await state();check(s.inventoryLayout.hotbar[4]==='battery'&&s.inventoryLayout.backpack[12]==='flare','Number key in inventory assigns and swaps without consuming');
  check(s.inventory.battery===initial.inventory.battery,'Assigning cannot use a supply');
  await slot('hotbar',4).click();await page.getByRole('button',{name:'In den Rucksack',exact:true}).click();
  await page.evaluate(()=>window.__nachtwache.hurt(20));
  await slot('hotbar',3).click();await page.getByRole('button',{name:'Benutzen',exact:true}).click();
  s=await state();check(s.health===100&&s.inventory.medkit===0&&s.inventoryLayout.hotbar[3]===null&&!s.active,'Inventory use heals once, frees exhausted stack and stays paused');
  await slot('backpack',0).click();await page.getByRole('button',{name:'Auf Hotbar-Platz 4 legen'}).click();
  await slot('hotbar',3).click();await page.getByRole('button',{name:'Ausrüsten',exact:true}).click();
  check((await state()).weapon==='pistol','Weapons can be equipped in inventory');
  await page.screenshot({path:'output/playwright/inventory-desktop.png'});
  await page.keyboard.press('i');
  await page.keyboard.press('2');check((await state()).weapon==='axe','Hotbar number equips its assigned weapon');
  await page.keyboard.press('4');check((await state()).weapon==='pistol','Moved weapon responds on its new hotbar number');
  await page.keyboard.press('1');
  s=await state();check(s.inventory.ration===0&&s.boosted>0&&s.inventoryLayout.hotbar[0]===null,'Hotbar uses reassigned supply and clears exhausted stack');
  const beforeEmpty=JSON.stringify(s.inventory);await page.keyboard.press('5');await page.keyboard.press('6');
  check(JSON.stringify((await state()).inventory)===beforeEmpty,'Empty hotbar and removed old shortcuts do not consume items');
  await page.keyboard.press('i');
  const paused=(await state()).elapsed;await page.keyboard.press('w');
  check((await state()).elapsed===paused,'World remains paused while managing inventory');
  const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('nachtwache.save.v1')));
  check(JSON.stringify(saved.progress.inventoryLayout)===JSON.stringify((await state()).inventoryLayout),'Every rearrangement saves immediately');
  await page.reload();await ready();await page.getByRole('button',{name:/^WEITERSPIELEN/}).click();
  await page.keyboard.press('i');
  s=await state();check(JSON.stringify(s.inventoryLayout)===JSON.stringify(saved.progress.inventoryLayout),'Exact layout survives a real browser reload');
  check(JSON.stringify(s.inventory)===JSON.stringify(saved.progress.inventory),'Reload preserves consumed supplies');
  await page.setViewportSize({width:720,height:900});
  check(await page.locator('.hotbar-grid>.inventory-slot').count()===5,'Narrow layout still has five slots');
  check(await page.locator('.field-journal').evaluate(el=>el.scrollWidth<=el.clientWidth+1),'Inventory fits a narrow viewport without horizontal overflow');
  await page.screenshot({path:'output/playwright/inventory-narrow.png'});
  await page.keyboard.press('Escape');check((await state()).active,'Escape returns to gameplay');
  await page.keyboard.press('m');await page.getByRole('button',{name:'Karte & Aufgaben',exact:true}).waitFor();
  check(await page.getByRole('button',{name:'Karte & Aufgaben',exact:true}).getAttribute('aria-pressed')==='true','M still opens map');
  await page.keyboard.press('Escape');
  await page.evaluate(()=>window.__nachtwache.menu());
  const legacy=await page.evaluate(()=>{const s=JSON.parse(localStorage.getItem('nachtwache.save.v1'));delete s.progress.inventoryLayout;localStorage.setItem('nachtwache.save.v1',JSON.stringify(s));return s.progress.inventory;});
  await page.reload();await ready();await page.getByRole('button',{name:/^WEITERSPIELEN/}).click();
  check(JSON.stringify((await state()).inventory)===JSON.stringify(legacy),'Legacy save loads without granting or losing supplies');
  await page.keyboard.press('i');
  await page.setViewportSize({width:1440,height:1080});
  return {passed:['I opens paused inventory','exactly five HUD slots','native drag occupied swap','click reordering','backpack free placement','stow and assign','keyboard assignment','paused item use','weapon selection','remapped hotbar actions','empty slots and old shortcuts','immediate save','real reload','narrow layout','Escape and map','legacy save compatibility']};
}
